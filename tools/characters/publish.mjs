#!/usr/bin/env node
/**
 * Publishes on-demand characters (dist/characters/*.glb) as assets of a GitHub Release, the
 * host the app downloads them from:
 *   https://github.com/<repo>/releases/download/<tag>/<id>.glb
 *
 *   npm run characters:publish            create the release if needed, upload, verify
 *   npm run characters:publish -- --dry   show what would be uploaded
 *
 * Needs the GitHub CLI (`gh`) signed in with write access to the repo. The repo must be public:
 * release assets of a private repo need a token, which the app does not have.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'tools/characters/characters.json'), 'utf8'),
);
const catalog = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'app/src/characters/catalog.json'), 'utf8'),
).characters;
const dry = process.argv.includes('--dry');

const { repo, tag } = manifest.release || {};
if (!repo || !tag) {
  console.error(
    'Set "release": { "repo": "owner/name", "tag": "characters-v1" } in tools/characters/characters.json',
  );
  process.exit(2);
}

const gh = (...args) =>
  execFileSync('gh', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();

const remote = catalog.filter((c) => !c.bundled);
const files = remote
  .map((c) => ({ c, file: path.join(ROOT, 'dist/characters', `${c.id}.glb`) }))
  .filter(({ c, file }) => {
    if (fs.existsSync(file)) return true;
    console.warn(`- ${c.id}: dist/characters/${c.id}.glb missing (run npm run characters)`);
    return false;
  });

if (files.length === 0) {
  console.log('No on-demand characters to publish (all characters are bundled).');
  process.exit(0);
}
console.log(`${files.length} character(s) → ${repo} release ${tag}`);
for (const { c, file } of files)
  console.log(`  ${c.id}.glb  ${(fs.statSync(file).size / 1024).toFixed(0)} KB`);
if (dry) process.exit(0);

try {
  gh('--version');
} catch {
  console.error(
    'GitHub CLI not found. Install it (https://cli.github.com) and run `gh auth login`.',
  );
  process.exit(2);
}
const visibility = gh('repo', 'view', repo, '--json', 'visibility', '--jq', '.visibility');
if (visibility !== 'PUBLIC') {
  console.error(
    `${repo} is ${visibility.toLowerCase()}: the app can't download private release assets. Use a public repo.`,
  );
  process.exit(2);
}
try {
  gh('release', 'view', tag, '--repo', repo);
} catch {
  gh(
    'release',
    'create',
    tag,
    '--repo',
    repo,
    '--title',
    `Characters (${tag})`,
    '--notes',
    'On-demand rower characters for RowRace 3D. Generated by tools/characters/publish.mjs.',
  );
  console.log(`created release ${tag}`);
}
gh('release', 'upload', tag, '--repo', repo, '--clobber', ...files.map((f) => f.file));
console.log('uploaded');

// Verify what the app will fetch: public URL, redirects followed, size matches the catalog.
let bad = 0;
for (const { c } of files) {
  const url = `https://github.com/${repo}/releases/download/${tag}/${c.id}.glb`;
  const res = await fetch(url, { redirect: 'follow' });
  const size = res.ok ? (await res.arrayBuffer()).byteLength : 0;
  const ok = res.ok && size === c.bytes;
  if (!ok) bad++;
  console.log(
    `${ok ? '✓' : '✗'} ${url} ${res.status} ${size} bytes${ok ? '' : ` (catalog: ${c.bytes})`}`,
  );
}
process.exitCode = bad ? 1 : 0;
