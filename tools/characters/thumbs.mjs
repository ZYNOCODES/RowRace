#!/usr/bin/env node
/**
 * Renders a 256×256 thumbnail per character (headless Chrome + the scene preview harness) into
 * app/assets/characters/thumbs/, and writes app/src/characters/thumbs.js (static requires).
 *   npm run characters:thumbs   (after npm run characters)
 * Needs Google Chrome/Chromium. Remote-only characters are read from dist/characters/.
 */
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const PREVIEW = path.join(ROOT, 'tools/scene-preview');
const OUT = path.join(ROOT, 'app/assets/characters/thumbs');
const THUMBS_JS = path.join(ROOT, 'app/src/characters/thumbs.js');
const catalog = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'app/src/characters/catalog.json'), 'utf8'),
).characters;
const chrome = ['google-chrome', 'google-chrome-stable', 'chromium', 'chromium-browser'].find(
  (c) => {
    try {
      execFileSync('which', [c], { stdio: 'ignore' });
      return true;
    } catch {
      return false;
    }
  },
);
if (!chrome) throw new Error('Chrome/Chromium not found');

// Bundle the harness and gather every character GLB next to it.
execFileSync(
  'npx',
  [
    'esbuild',
    'tools/scene-preview/main.js',
    '--bundle',
    '--format=esm',
    '--outfile=tools/scene-preview/dist/preview.js',
  ],
  { cwd: ROOT, stdio: 'ignore' },
);
const chars = path.join(PREVIEW, 'characters');
fs.rmSync(chars, { recursive: true, force: true });
fs.mkdirSync(chars, { recursive: true });
for (const c of catalog) {
  const src = path.join(
    ROOT,
    c.bundled ? 'app/assets/characters' : 'dist/characters',
    `${c.id}.glb`,
  );
  if (fs.existsSync(src)) fs.copyFileSync(src, path.join(chars, `${c.id}.glb`));
}

const port = 8766;
const server = spawn('python3', ['-m', 'http.server', String(port), '--directory', PREVIEW], {
  stdio: 'ignore',
});
await new Promise((r) => setTimeout(r, 800));
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'rowrace-thumbs-'));
fs.mkdirSync(OUT, { recursive: true });
const done = [];
try {
  for (const c of catalog) {
    if (!fs.existsSync(path.join(chars, `${c.id}.glb`))) {
      console.log(`- ${c.id}: no GLB, skipped`);
      continue;
    }
    const out = path.join(OUT, `${c.id}.png`);
    execFileSync(
      chrome,
      [
        '--headless=new',
        '--no-first-run',
        `--user-data-dir=${profile}`,
        '--use-angle=swiftshader',
        '--enable-unsafe-swiftshader',
        '--hide-scrollbars',
        '--default-background-color=00000000',
        '--window-size=256,256',
        '--virtual-time-budget=5000',
        `--screenshot=${out}`,
        `http://localhost:${port}/?thumb=${c.id}`,
      ],
      { stdio: 'ignore', timeout: 90000 },
    );
    done.push(c.id);
    console.log(`✓ ${c.id}`);
  }
} finally {
  server.kill();
  fs.rmSync(profile, { recursive: true, force: true });
}
const lines = done
  .map((id) => `  ${JSON.stringify(id)}: require('../../assets/characters/thumbs/${id}.png'),`)
  .join('\n');
fs.writeFileSync(
  THUMBS_JS,
  `// Generated by tools/characters/thumbs.mjs. Do not edit.\nexport default {\n${lines}\n};\n`,
);
console.log(`${done.length} thumbnails`);
